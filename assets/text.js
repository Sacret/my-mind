/**
 * Мелкие помощники для текста интерфейса.
 *
 * plural — русское согласование существительного с числом. Форм три, и выбор
 * идёт по последней цифре, кроме второго десятка: 11–14 всегда берут «many».
 *
 *   plural(1,  "карточка", "карточки", "карточек")  → карточка
 *   plural(3,  ...)                                  → карточки
 *   plural(11, ...)                                  → карточек
 *   plural(21, ...)                                  → карточка
 */
function plural(n, one, few, many) {
  const t = n % 10, h = n % 100;
  if (t === 1 && h !== 11) return one;
  if (t >= 2 && t <= 4 && (h < 12 || h > 14)) return few;
  return many;
}
